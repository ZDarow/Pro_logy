def xor_bytes(data):
    """XOR всех байт"""
    result = 0
    for b in data:
        result ^= b
    return result

def find_constant(cmd):
    """Найти константу для команды: CRC = XOR(data) XOR constant"""
    data = cmd[:-1]
    crc = cmd[-1]
    xor_data = xor_bytes(data)
    constant = crc ^ xor_data
    return constant

def calculate_crc(data, constant):
    """Расчёт CRC с константой"""
    return xor_bytes(data) ^ constant

