def xor_crc(data):
    """XOR всех байт"""
    crc = 0
    for byte in data:
        crc ^= byte
    return crc

def sum_crc(data):
    """Сумма всех байт mod 256"""
    return sum(data) & 0xFF

def xor_except_last(data):
    """XOR всех байт кроме последнего"""
    crc = 0
    for byte in data[:-1]:
        crc ^= byte
    return crc

def xor_except_first_last(data):
    """XOR всех байт кроме первого и последнего"""
    if len(data) < 3:
        return 0
    crc = 0
    for byte in data[1:-1]:
        crc ^= byte
    return crc

def sum_except_last(data):
    """Сумма всех байт кроме последнего mod 256"""
    return sum(data[:-1]) & 0xFF

def custom_crc_1(data):
    """XOR с начального значения"""
    crc = 0xC0
    for byte in data[1:]:
        crc ^= byte
    return crc

def custom_crc_2(data):
    """Сумма + XOR комбинация"""
    s = sum(data[:-1]) & 0xFF
    x = 0
    for byte in data[:-1]:
        x ^= byte
    return (s + x) & 0xFF

def custom_crc_3(data):
    """XOR с инверсией"""
    crc = 0
    for byte in data[:-1]:
        crc ^= byte
    return (~crc) & 0xFF

def custom_crc_4(data):
    """Сумма с вычитанием"""
    return (0x100 - (sum(data[:-1]) & 0xFF)) & 0xFF

def analyze_crc():
    """Анализ всех команд"""
    print("╔═══════════════════════════════════════════════════════════════════╗")
    print("║  PROLOGY CRC Analysis                                             ║")
    print("╚═══════════════════════════════════════════════════════════════════╝")
    print()
    
    algorithms = [
        ("XOR all", xor_crc),
        ("XOR except last", xor_except_last),
        ("XOR except first+last", xor_except_first_last),
        ("Sum mod 256", sum_crc),
        ("Sum except last", sum_except_last),
        ("XOR from 0xC0", custom_crc_1),
        ("Sum + XOR", custom_crc_2),
        ("XOR inverted", custom_crc_3),
        ("0x100 - Sum", custom_crc_4),
    ]
    
    matches = {name: 0 for name, _ in algorithms}
    total = len(COMMANDS)
    
    for cmd, desc in COMMANDS:
        actual_crc = cmd[-1]
        
        print(f"Command: {cmd.hex().upper()}")
        print(f"Length: {len(cmd)} bytes")
        print(f"Actual CRC: 0x{actual_crc:02X}")
        print(f"Description: {desc}")
        print()
        
        for name, func in algorithms:
            try:
                calc = func(cmd)
                match = "✅" if calc == actual_crc else "❌"
                if calc == actual_crc:
                    matches[name] += 1
                print(f"  {match} {name:25} = 0x{calc:02X}")
            except Exception as e:
                print(f"  ❓ {name:25} = ERROR: {e}")
        
        print()
        print("─" * 75)
        print()
    
    print()
    print("╔═══════════════════════════════════════════════════════════════════╗")
    print("║  RESULTS                                                          ║")
    print("╚═══════════════════════════════════════════════════════════════════╝")
    print()
    
    for name, count in sorted(matches.items(), key=lambda x: x[1], reverse=True):
        percent = (count / total) * 100
        bar = "█" * int(percent / 5)
        print(f"  {name:25} : {count:3}/{total} ({percent:5.1f}%) {bar}")
    
    print()
    
    # Поиск паттернов
    print("╔═══════════════════════════════════════════════════════════════════╗")
    print("║  PATTERN ANALYSIS                                                 ║")
    print("╚═══════════════════════════════════════════════════════════════════╝")
    print()
    
    # Группировка по длине
    by_length = {}
    for cmd, desc in COMMANDS:
        length = len(cmd)
        if length not in by_length:
            by_length[length] = []
        by_length[length].append((cmd, desc))
    
    for length in sorted(by_length.keys()):
        print(f"Length {length} bytes ({len(by_length[length])} commands):")
        cmds = by_length[length]
        
        # Проверка XOR except last для этой длины
        matches_xor = 0
        for cmd, desc in cmds:
            if xor_except_last(cmd) == cmd[-1]:
                matches_xor += 1
        
        print(f"  XOR except last matches: {matches_xor}/{len(cmds)}")
        
        # Проверка Sum except last
        matches_sum = 0
        for cmd, desc in cmds:
            if sum_except_last(cmd) == cmd[-1]:
                matches_sum += 1
        
        print(f"  Sum except last matches: {matches_sum}/{len(cmds)}")
        print()

if __name__ == "__main__":
    analyze_crc()
