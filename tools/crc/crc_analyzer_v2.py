            diff = (crc - xor_data) & 0xFF
            
            print(f"  Data: {data.hex().upper()}")
            print(f"  CRC:  0x{crc:02X}")
            print(f"  XOR(data):     0x{xor_data:02X} (diff: 0x{diff:02X})")
